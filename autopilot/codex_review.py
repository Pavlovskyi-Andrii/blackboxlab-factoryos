"""Automatic Codex review of open pull requests through the FactoryOS agent relay (owner 2026-11-13: "делай ревью PR
через Codex автоматически").

Runs on the EC2 worker between tasks, as the Claude side of the relay (dedicated FACTORY_CLAUDE_RELAY_TOKEN, never the
broad worker token). One call does two cheap things and never runs a model itself:
1. collect Codex answers from Claude's relay inbox and post each one as a PR comment (advisory, not an approval);
2. send at most one new review request: an open, non-draft PR whose current head commit has not been reviewed yet.

Bounds: one request per pass, MAX_PER_DAY requests per UTC day, one review per head commit, and a pause of
MIN_GAP_SECONDS per PR so a series of quick pushes is reviewed once. The diff is truncated to MAX_DIFF characters and
anything credential-shaped is redacted before it leaves the machine. Codex itself runs under the separate, isolated
codex relay service (deploy/codex-relay). Nothing here merges, approves or changes code.
"""
from __future__ import annotations

import json
import os
import pathlib
import re
import subprocess
import sys
import time

try:
    from .agent_relay_client import AgentRelayClient, RelayHTTPError, read_token
except ImportError:
    from agent_relay_client import AgentRelayClient, RelayHTTPError, read_token
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from agent_secret_scan import SECRET_SCAN  # noqa: E402

REPO_SLUG = os.environ.get("AUTOPILOT_REVIEW_REPO", "Pavlovskyi-Andrii/blackboxlab-factoryos")
ENABLED = os.environ.get("AUTOPILOT_CODEX_REVIEW", "1").strip().lower() in {"1", "true", "yes", "on"}
TOKEN_FILE = os.environ.get("FACTORY_CLAUDE_RELAY_TOKEN_FILE", "/root/claude-relay.token")
MAX_DIFF = 20000
MAX_PER_DAY = 12
MIN_GAP_SECONDS = 1800
MAX_INBOX = 5
COMMENT_HEAD = "🤖 **Codex review** · automatic, via the FactoryOS agent relay · advisory only, not an approval"


def log(message: str) -> None:
    print(f"codex-review: {message}", file=sys.stderr, flush=True)


def gh(*args: str, input_text: str | None = None, runner=subprocess.run) -> tuple[int, str]:
    result = runner(["gh", *args], text=True, capture_output=True, input=input_text, timeout=120, check=False)
    return result.returncode, (result.stdout or "").strip()


def claude_token() -> str:
    token = read_token("FACTORY_CLAUDE_RELAY_TOKEN")
    if not token:
        try:
            token = pathlib.Path(TOKEN_FILE).read_text(encoding="utf-8").strip()
        except OSError:
            token = ""
    return token


def default_client():
    url, token = os.environ.get("FACTORYOS_URL", "").rstrip("/"), claude_token()
    return AgentRelayClient(url, token) if url and token else None


def _load(path: pathlib.Path) -> dict:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def _save(path: pathlib.Path, state: dict) -> None:
    state["pending"] = dict(list((state.get("pending") or {}).items())[-50:])
    state["reviewed"] = (state.get("reviewed") or [])[-300:]
    path.write_text(json.dumps(state, indent=1), encoding="utf-8")


def review_body(pr: dict, diff: str) -> str:
    diff = SECRET_SCAN.sub("[REDACTED]", diff)
    note = ""
    if len(diff) > MAX_DIFF:
        diff, note = diff[:MAX_DIFF], f"\n[diff truncated to {MAX_DIFF} characters]"
    description = SECRET_SCAN.sub("[REDACTED]", str(pr.get("body") or ""))[:1500]
    return (f"Pull request #{pr['number']}: {pr.get('title', '')}\nBranch: {pr.get('headRefName', '')} · "
            f"head {pr['headRefOid'][:12]} · +{pr.get('additions', '?')}/-{pr.get('deletions', '?')}\n\n"
            f"Description:\n{description}\n\nDiff:\n{diff}{note}")


def comment_text(item: dict, head: str) -> str:
    body = str(item.get("body") or "").strip()
    if item.get("kind") == "blocker":
        body = "Codex did not send a review: " + body
    return (f"{COMMENT_HEAD}\n\n{body}\n\n— reviewed head `{head[:12]}`\n\n---\n"
            "_Generated by Codex (ChatGPT subscription) through FactoryOS; posted by the Claude worker._")


def collect(client, state: dict, *, gh_fn=gh) -> int:
    """Post Codex answers to their PRs. Every claimed message is ACKed so the inbox never fills up."""
    posted, pending = 0, state.setdefault("pending", {})
    for _ in range(MAX_INBOX):
        item = client.claim()
        if not item:
            break
        target = pending.get(str(item.get("reply_to") or ""))
        if target and item.get("from_agent") == "codex":
            code, _ = gh_fn("pr", "comment", str(target["pr"]), "-R", REPO_SLUG, "--body-file", "-",
                            input_text=comment_text(item, target["head"]))
            if code != 0:
                log(f"could not comment on PR #{target['pr']}; will retry after the lease")
                continue                       # no ACK: the relay redelivers it (bounded by its attempts)
            pending.pop(str(item.get("reply_to")), None)
            posted += 1
            log(f"posted Codex review on PR #{target['pr']} ({target['head'][:12]})")
        client.ack(item["message_id"], item["claim_token"])
    return posted


def request_one(client, state: dict, *, gh_fn=gh, now: float | None = None) -> str:
    current = time.time() if now is None else now
    day = time.strftime("%Y-%m-%d", time.gmtime(current))
    sent = state.setdefault("sent", {})
    if int(sent.get(day, 0)) >= MAX_PER_DAY:
        return ""
    code, out = gh_fn("pr", "list", "-R", REPO_SLUG, "--state", "open", "--limit", "30", "--json",
                      "number,title,headRefOid,headRefName,isDraft,additions,deletions,body")
    if code != 0:
        log("gh pr list failed")
        return ""
    try:
        prs = json.loads(out or "[]")
    except ValueError:
        return ""
    reviewed, last = set(state.setdefault("reviewed", [])), state.setdefault("last", {})
    for pr in sorted(prs, key=lambda p: p.get("number", 0)):
        key = f"{pr['number']}:{pr['headRefOid']}"
        if pr.get("isDraft") or key in reviewed or current - float(last.get(str(pr["number"]), "-inf")) < MIN_GAP_SECONDS:
            continue
        code, diff = gh_fn("pr", "diff", str(pr["number"]), "-R", REPO_SLUG)
        if code != 0:
            continue
        try:
            msg = client.send("codex", review_body(pr, diff), kind="review", task_id=f"pr-{pr['number']}",
                              idempotency_key=f"review-{pr['number']}-{pr['headRefOid'][:16]}")
        except RelayHTTPError as exc:
            log(f"review request for PR #{pr['number']} refused: {exc.status} {exc.code}")
            state["reviewed"].append(key)      # do not retry the same head forever
            return ""
        state["pending"][msg["message_id"]] = {"pr": pr["number"], "head": pr["headRefOid"]}
        state["reviewed"].append(key)
        last[str(pr["number"])] = current
        sent[day] = int(sent.get(day, 0)) + 1
        state["sent"] = {d: n for d, n in sent.items() if d >= time.strftime("%Y-%m-%d", time.gmtime(current - 7 * 86400))}
        log(f"asked Codex to review PR #{pr['number']} ({pr['headRefOid'][:12]})")
        return msg["message_id"]
    return ""


def run_once(state_path: pathlib.Path, *, client=None, gh_fn=gh, now: float | None = None) -> str:
    """idle | posted | requested | off. Never raises: a review problem must not stop the worker."""
    if not ENABLED:
        return "off"
    client = client or default_client()
    if client is None:
        return "off"
    state = _load(state_path)
    try:
        posted = collect(client, state, gh_fn=gh_fn)
        requested = request_one(client, state, gh_fn=gh_fn, now=now)
    except Exception as exc:                   # network, relay or gh trouble: try again next pass
        log(f"skipped this pass: {type(exc).__name__}")
        _save(state_path, state)
        return "idle"
    _save(state_path, state)
    return "posted" if posted else ("requested" if requested else "idle")
